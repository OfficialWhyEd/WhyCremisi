// Testi della schermata di accesso che funziona oggi (SetupScreen).
// La lingua si sceglie con guessLang/saveLang di i18n.js, la stessa del
// nuovo primo avvio: chi la cambia qui la trova uguale là.

const CHIAVE_LINGUA = 'whycremisi_lang'

export function guessLang() {
  try {
    const salvata = localStorage.getItem(CHIAVE_LINGUA)
    if (salvata === 'it' || salvata === 'en') return { lang: salvata, guessed: false }
  } catch { /* storage non disponibile */ }
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'it'
  return { lang: nav.toLowerCase().startsWith('it') ? 'it' : 'en', guessed: true }
}

export function saveLang(lang) {
  try { localStorage.setItem(CHIAVE_LINGUA, lang) } catch { /* ignora */ }
}

